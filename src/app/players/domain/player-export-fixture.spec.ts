import { writeFileSync } from 'node:fs';

import { SCHEMA_VERSION, SIM_VERSION } from '@app/engine/domain/version';

import { decodePlayerExport, encodePlayerExport, exportFileName } from './player-export-logic';
import { exportFixtureContent } from './testing/export-fixture';
import { EXPORT_V1_CONTENT, EXPORT_V1_FILE_NAME } from './testing/export-v1';

// Frozen export file of format version 1 (TS §10.1, AP 6.1): it must stay readable, and a fresh
// export of the same game must have its structure. Until 1.0, a new `SIM_VERSION` or
// `SCHEMA_VERSION` makes it outdated: regenerate it with
// `UPDATE_EXPORT_FIXTURE=1 npx vitest run src/app/players/domain/player-export-fixture.spec.ts`.
// From 1.0 on it is never changed; a new format version gets a new fixture next to it.

const UPDATE = process.env['UPDATE_EXPORT_FIXTURE'] === '1';

/** Paths and types of every value, lists as `[]`: the structure of a decoded export. */
function shape(value: unknown, path = '$', into = new Set<string>()): Set<string> {
  if (value instanceof Map) {
    into.add(`${path}:Map`);
    value.forEach((item, key) => {
      shape(key, `${path}.key`, into);
      shape(item, `${path}.value`, into);
    });
  } else if (ArrayBuffer.isView(value)) {
    into.add(`${path}:${value.constructor.name}`);
  } else if (Array.isArray(value)) {
    into.add(`${path}:Array`);
    value.forEach((item) => shape(item, `${path}[]`, into));
  } else if (value !== null && typeof value === 'object') {
    into.add(`${path}:object`);
    Object.entries(value).forEach(([key, item]) => shape(item, `${path}.${key}`, into));
  } else {
    into.add(`${path}:${value === null ? 'null' : typeof value}`);
  }
  return into;
}

function sorted(set: Set<string>): string[] {
  return [...set].sort();
}

describe('export fixture of format version 1', () => {
  it.runIf(UPDATE)('is regenerated on request', async () => {
    const text = await encodePlayerExport(exportFixtureContent());
    const lines = text.match(/.{1,80}/g) ?? [];
    writeFileSync(
      new URL('./testing/export-v1.ts', import.meta.url),
      [
        '// Frozen export file of format version 1 (TS §10.1), generated by',
        '// `player-export-fixture.spec.ts` from `exportFixtureContent()`. Do not edit.',
        '',
        `export const EXPORT_V1_FILE_NAME = 'Export-Fixture-2030-05-15.pgo';`,
        '',
        'export const EXPORT_V1_CONTENT = [',
        ...lines.map((line) => `  '${line}',`),
        "].join('');",
        '',
      ].join('\n'),
    );
  });

  it('is read with the current versions', async () => {
    const decoded = await decodePlayerExport(EXPORT_V1_CONTENT);
    expect(decoded.ok ? decoded.export : decoded.error).toMatchObject({
      formatVersion: 1,
      simVersion: SIM_VERSION,
      schemaVersion: SCHEMA_VERSION,
      player: { name: 'Export Fixture', seed: 'mini-1' },
    });
    if (decoded.ok) {
      expect(exportFileName(decoded.export.player.name, decoded.export.state.tick)).toBe(
        EXPORT_V1_FILE_NAME,
      );
    }
  });

  it('has the structure of a fresh export of the same game', async () => {
    const decoded = await decodePlayerExport(EXPORT_V1_CONTENT);
    if (!decoded.ok) {
      throw new Error(`fixture not readable: ${decoded.error}`);
    }
    const fresh = await decodePlayerExport(await encodePlayerExport(exportFixtureContent()));
    if (!fresh.ok) {
      throw new Error(`fresh export not readable: ${fresh.error}`);
    }
    expect(sorted(shape(fresh.export))).toEqual(sorted(shape(decoded.export)));
  });
});
