// `break`: baseline of AP 0.5 (94.6 %) minus 3 points (TS §14.1). A CI shard doesn't break on its
// own score; `tools/mutation-score.mjs` checks the score of all shards together.
export const BREAK_THRESHOLD = 91;

const shard = process.env['MUTATION_SHARD'];
const shardIndex = shard === undefined ? undefined : Number(shard) - 1;
if (shardIndex !== undefined && MUTATION_SHARDS[shardIndex] === undefined) {
  throw new Error(`MUTATION_SHARD must be 1 to ${MUTATION_SHARDS.length}, got "${shard}"`);
}

